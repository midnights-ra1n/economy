export const LOCALES = ["fr", "en"] as const;
export type Locale = (typeof LOCALES)[number];
export const LOCALE_NAMES: Record<Locale, string> = { fr: "Français", en: "English" };
/** BCP 47 tag for Intl (numbers, dates, currencies). */
export const INTL: Record<Locale, string> = { fr: "fr-FR", en: "en-US" };
export const isLocale = (v: unknown): v is Locale => LOCALES.includes(v as Locale);

/** First supported language of an Accept-Language header, English otherwise. */
export function pickLocale(acceptLanguage: string | null): Locale {
  const tags = (acceptLanguage ?? "").split(",").map((t) => t.trim().slice(0, 2).toLowerCase());
  return tags.find(isLocale) ?? "en";
}

type Vars = Record<string, string | number>;
type PluralKey = Key extends infer K ? (K extends `${infer B}.one` ? B : never) : never;

const dicts: Record<Locale, Record<Key, string>> = { fr, en };
const cache = new Map<Locale, ReturnType<typeof make>>();

function make(locale: Locale) {
  const dict = dicts[locale];
  const rules = new Intl.PluralRules(INTL[locale]);
  // Unknown placeholders stay as-is so rich() can still find them.
  const t = (key: Key, vars: Vars = {}) => dict[key].replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  const tn = (key: PluralKey, n: number, vars: Vars = {}) =>
    t(`${key}.${rules.select(n) === "one" ? "one" : "other"}` as Key, { n: n.toLocaleString(INTL[locale]), ...vars });
  /**
   * Message of a thrown error. Errors thrown with a dictionary key ("err.locked", or "err.backupValue|detail"
   * to fill {x}) are translated; any other message passes through.
   */
  const te = (e: unknown, fallback: Key = "err.unexpected") => {
    if (!(e instanceof Error)) return t(fallback);
    const [key, x] = e.message.split("|");
    return key in dict ? t(key as Key, x === undefined ? {} : { x }) : e.message;
  };
  /** Like t, with placeholders filled by React nodes (links, amounts, bold text). */
  const rich = (key: Key, nodes: Record<string, ReactNode>, vars: Vars = {}): ReactNode[] =>
    t(key, vars).split(/\{(\w+)\}/).map((part, i) => createElement(Fragment, { key: i }, i % 2 ? nodes[part] : part));
  return { locale, intl: INTL[locale], t, tn, te, rich };
}

export function translator(locale: Locale) {
  if (!cache.has(locale)) cache.set(locale, make(locale));
  return cache.get(locale)!;
}

export type T = ReturnType<typeof translator>;
